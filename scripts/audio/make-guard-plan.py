#!/usr/bin/env python3
"""Emit the typed guard plan from the frozen manifest + control map.

The Rust guardian parses this line format; it deliberately has no JSON parser, so
every value it can act on is restated here in the narrowest possible shape and
cross-checked against the control map.
"""
import hashlib
import json
import os
import sys

TYPE_MAP = {"BOOL": "BOOL", "BOOLEAN": "BOOL", "INT": "INT", "INTEGER": "INT",
            "ENUM": "ENUM", "ENUMERATED": "ENUM"}


def main():
    srv = sys.argv[1]
    run_id = sys.argv[2]
    out = sys.argv[3] if len(sys.argv) > 3 else os.path.join(srv, "guard-plan.txt")
    card = sys.argv[4] if len(sys.argv) > 4 else "0"
    fake_root = sys.argv[5] if len(sys.argv) > 5 else ""

    manifest_path = os.path.join(srv, "trial-manifest.json")
    cmap_path = os.path.join(srv, "control-map.json")
    with open(manifest_path, "rb") as fh:
        manifest_bytes = fh.read()
    manifest = json.loads(manifest_bytes)
    cmap = json.load(open(cmap_path))

    sha = hashlib.sha256(manifest_bytes).hexdigest()
    boot_id = open("/proc/sys/kernel/random/boot_id").read().strip()

    lines = [
        "# generated by make-guard-plan.py -- do not edit by hand",
        "run_id %s" % run_id,
        "boot_id %s" % boot_id,
        "manifest_sha %s" % sha,
        "card %s" % card,
        "heartbeat_ms 250",
        "expiry_ms 1500",
        "max_seconds 420",
    ]
    if fake_root:
        lines.append("fake_root %s" % fake_root)

    controls = cmap.get("controls") or {}
    for stop in manifest.get("stop_actions") or []:
        name = stop["name"]
        values = stop["values"]
        entry = controls.get(name)
        if entry is None:
            raise SystemExit("stop target %r is not in the audited control map" % name)
        ty = TYPE_MAP.get(entry.get("type") or "")
        if ty is None:
            raise SystemExit("control %r has unsupported type %r" % (name, entry.get("type")))
        count = int(entry.get("count") or 1)
        if count != len(values):
            raise SystemExit("control %r: map says %d values, manifest writes %d"
                             % (name, count, len(values)))
        lines.append("stop %s|%s|%d|%s" % (name, ty, count,
                                           ",".join(str(int(v)) for v in values)))

    # The amplifiers must leave their driver before the codec module can unload;
    # these two addresses are the audited TFA9874 pair on I2C bus 15 (run
    # 20261112t1115z binding evidence: 15-0034 -> channel 0 Left, 15-0035 ->
    # channel 1 Right). They are emitted as plan lines, so they are part of the
    # guardian's whitelist rather than being hardcoded in its code.
    rmmod_list = manifest.get("rmmod") or ["snd_soc_tfa2"]
    for mod in rmmod_list:
        if mod == "snd_soc_tfa2":
            for addr in ("15-0034", "15-0035"):
                lines.append("unbind %s" % addr)
    for mod in rmmod_list:
        lines.append("rmmod %s" % mod)

    with open(out, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    os.chmod(out, 0o600)
    print("plan written:", out)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
