#!/usr/bin/env bash
# Host-only preparation. Never calls ADB/fastboot or chooses a phone partition.
set -euo pipefail

build_dir=$(realpath -m -- "${1:?Usage: prepare-debian-rootfs.sh fresh-linux-build-dir authorized-key.pub}")
public_key=$(realpath -e -- "${2:?An SSH public key is required; never pass a private key}")
rootfs="$build_dir/rootfs"
[[ $EUID == 0 ]] || { printf 'Run in the Linux build host as root (debootstrap/chroot only).\n' >&2; exit 1; }
[[ ! -e "$rootfs" && ! -e "$build_dir/packages" ]] || { printf 'Use a fresh directory; existing rootfs/packages are preserved.\n' >&2; exit 1; }
grep -Eq '^ssh-ed25519 [A-Za-z0-9+/=]+( .*)?$' "$public_key" || { printf 'Expected one Ed25519 public key.\n' >&2; exit 1; }
[[ $(wc -l < "$public_key") -le 1 ]] || { printf 'Expected one public key.\n' >&2; exit 1; }
for tool in debootstrap qemu-aarch64-static gpgv chroot python3; do
  command -v "$tool" >/dev/null || { printf 'Missing host tool: %s\n' "$tool" >&2; exit 1; }
done
grep -q '^enabled' /proc/sys/fs/binfmt_misc/qemu-aarch64 || { printf 'ARM64 binfmt is not enabled.\n' >&2; exit 1; }
mkdir -p -- "$build_dir/packages"
probe=$(mktemp -d "$build_dir/.case-probe.XXXXXX")
touch "$probe/lower"
if [[ -e "$probe/LOWER" ]]; then rm -- "$probe/lower"; rmdir -- "$probe"; printf 'Use a case-sensitive Linux filesystem.\n' >&2; exit 1; fi
rm -- "$probe/lower"
rmdir -- "$probe"
exec > >(tee "$build_dir/rootfs-build.log") 2>&1
export DEBIAN_FRONTEND=noninteractive LC_ALL=C
unset http_proxy https_proxy all_proxy HTTP_PROXY HTTPS_PROXY ALL_PROXY

debootstrap --arch=arm64 --foreign --variant=minbase --force-check-gpg \
  --keyring=/usr/share/keyrings/debian-archive-keyring.gpg \
  --include=systemd-sysv,udev,initramfs-tools,kmod,openssh-server,iproute2,ca-certificates,busybox-static,dropbear-bin,sudo \
  trixie "$rootfs" https://deb.debian.org/debian
# Archive the actual authenticated inputs before debootstrap/apt cleanup.
find "$rootfs/var/cache/apt/archives" -maxdepth 1 -name '*.deb' -type f -exec cp -- '{}' "$build_dir/packages/" \;
cp -- /usr/bin/qemu-aarch64-static "$rootfs/usr/bin/qemu-aarch64-static"
chroot "$rootfs" /usr/bin/qemu-aarch64-static /bin/sh /debootstrap/debootstrap --second-stage
cat > "$rootfs/usr/sbin/policy-rc.d" <<'EOF'
#!/bin/sh
exit 101
EOF
chmod 755 "$rootfs/usr/sbin/policy-rc.d"
cat > "$rootfs/etc/apt/sources.list" <<'EOF'
deb https://deb.debian.org/debian trixie main
deb https://deb.debian.org/debian trixie-updates main
deb https://deb.debian.org/debian-security trixie-security main
EOF
chroot "$rootfs" /usr/bin/env DEBIAN_FRONTEND=noninteractive LC_ALL=C apt-get \
  -o Acquire::https::Proxy=DIRECT -o Acquire::http::Proxy=DIRECT update
chroot "$rootfs" /usr/bin/env DEBIAN_FRONTEND=noninteractive LC_ALL=C apt-get \
  -o Acquire::https::Proxy=DIRECT -o Acquire::http::Proxy=DIRECT \
  -o APT::Keep-Downloaded-Packages=true -o Dpkg::Use-Pty=0 --no-install-recommends -y dist-upgrade
find "$rootfs/var/cache/apt/archives" -maxdepth 1 -name '*.deb' -type f -exec cp -- '{}' "$build_dir/packages/" \;
chroot "$rootfs" useradd --create-home --shell /bin/bash --groups sudo debian
install -d -m 700 "$rootfs/home/debian/.ssh"
install -m 600 "$public_key" "$rootfs/home/debian/.ssh/authorized_keys"
chroot "$rootfs" chown -R debian:debian /home/debian/.ssh
printf 'debian ALL=(ALL:ALL) NOPASSWD: ALL\n' > "$rootfs/etc/sudoers.d/90-kebab-local-admin"
chmod 440 "$rootfs/etc/sudoers.d/90-kebab-local-admin"
cat > "$rootfs/etc/ssh/sshd_config.d/90-kebab.conf" <<'EOF'
PasswordAuthentication no
KbdInteractiveAuthentication no
PermitRootLogin no
AllowUsers debian
EOF
printf 'kebab-debian13\n' > "$rootfs/etc/hostname"
printf '127.0.0.1 localhost\n127.0.1.1 kebab-debian13\n' > "$rootfs/etc/hosts"
# Do not export identities generated by package installation under emulation.
find "$rootfs/etc/ssh" -maxdepth 1 -type f -name 'ssh_host_*' -delete
cat > "$rootfs/etc/systemd/system/kebab-ssh-hostkeys.service" <<'EOF'
[Unit]
Description=Generate local SSH host keys on first device boot
Before=ssh.service
[Service]
Type=oneshot
ExecStart=/usr/bin/ssh-keygen -A
RemainAfterExit=yes
[Install]
WantedBy=multi-user.target
EOF
mkdir -p "$rootfs/etc/systemd/system/ssh.service.d" "$rootfs/etc/systemd/system/multi-user.target.wants"
cat > "$rootfs/etc/systemd/system/ssh.service.d/hostkeys.conf" <<'EOF'
[Unit]
Requires=kebab-ssh-hostkeys.service
After=kebab-ssh-hostkeys.service
EOF
ln -s ../kebab-ssh-hostkeys.service "$rootfs/etc/systemd/system/multi-user.target.wants/kebab-ssh-hostkeys.service"
: > "$rootfs/etc/machine-id"
if [[ -f "$rootfs/var/lib/dbus/machine-id" && ! -L "$rootfs/var/lib/dbus/machine-id" ]]; then : > "$rootfs/var/lib/dbus/machine-id"; fi
rm -- "$rootfs/usr/bin/qemu-aarch64-static" "$rootfs/usr/sbin/policy-rc.d"
chroot "$rootfs" dpkg-query -W -f='${Package}\t${Version}\t${Architecture}\n' > "$build_dir/rootfs-packages.tsv"
python3 - "$build_dir" "$public_key" <<'PY'
import datetime, hashlib, json, pathlib, sys
b, key = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
packages = [{"file": f.name, "bytes": f.stat().st_size, "sha256": hashlib.sha256(f.read_bytes()).hexdigest()}
            for f in sorted((b/'packages').glob('*.deb'))]
(b/'rootfs-manifest.json').write_text(json.dumps({
    "created_at_utc": datetime.datetime.now(datetime.timezone.utc).isoformat(),
    "distribution": "Debian 13 trixie", "architecture": "arm64",
    "package_repository_signatures_checked": True, "packages": packages,
    "installed_packages_sha256": hashlib.sha256((b/'rootfs-packages.tsv').read_bytes()).hexdigest(),
    "authorized_public_key_sha256": hashlib.sha256(key.read_bytes()).hexdigest(),
    "login_user": "debian", "password_login": False, "root_login": False,
    "local_admin_via_sudo": True, "ssh_host_keys_in_export": False,
    "phase": "base_userspace_prepared", "kernel_modules_installed": False,
    "firmware_installed": False, "rootfs_destination_selected": False,
    "hardware_boot_verified": False,
}, indent=2)+'\n')
print('Prepared ARM64 base userspace:', b/'rootfs')
PY
